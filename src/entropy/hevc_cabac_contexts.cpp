void HevcCabacContextSet::init(HevcSliceType slice_type, int32_t slice_qp) noexcept {
    int32_t qp = std::clamp(slice_qp, 0, 51);

    for (size_t i = 0; i < HEVC_NUM_CABAC_CONTEXTS; ++i) {
        uint8_t init_val = 154;
        if (slice_type == HevcSliceType::B) {
            init_val = HEVC_CTX_INIT_TABLE[i].init_b;
        } else if (slice_type == HevcSliceType::P) {
            init_val = HEVC_CTX_INIT_TABLE[i].init_p;
        } else {
            init_val = HEVC_CTX_INIT_TABLE[i].init_i;
        }

        // Standard HEVC derivation (Section 9.3.2.2):
        // slope = (init_value >> 4) * 5 - 4
        // offset = ((init_value & 15) << 3) - 16
        int32_t slope = static_cast<int32_t>(init_val >> 4) * 5 - 4;
        int32_t offset = (static_cast<int32_t>(init_val & 0x0F) << 3) - 16;

        contexts_[i].init(qp, slope, offset);
    }
}

